# Defined lists
list1 = [1, 2, 3]
list2 = [4, 5, 6]

# 1. Join both lists
joined_list = list1 + list2
print("Joined List:", joined_list)

# 2. Repeat list1 three times
repeated_list = list1 * 3
print("Repeated List:", repeated_list)

# 3. Check if 2 is in list1
is_present = 2 in list1
print("Is 2 in list1?:", is_present)
